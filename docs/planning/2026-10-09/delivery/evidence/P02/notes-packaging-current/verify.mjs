// Package the current notes behavior without changing reviewer files or running a server.
import { readFileSync, writeFileSync, copyFileSync, readdirSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { Script } from 'node:vm';
import assert from 'node:assert/strict';

const root = 'C:/Users/RyanHelms/GitHub/agentmux';
const cache = dirname(fileURLToPath(import.meta.url));
const read = path => readFileSync(resolve(root, path));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const notesRoot = 'docs/reviews/agentmux-visual-review/notes';
const notes = () => Object.fromEntries(readdirSync(resolve(root, notesRoot)).sort().map(name => [name, hash(read(notesRoot + '/' + name))]));
const outputs = ['docs/planning/2026-10-09/agentmux-visual-review.html', 'docs/planning/2026-10-09/review-site/build-report.json', 'docs/reviews/agentmux-visual-review/document-version.json'];
const sources = ['docs/reviews/src/features/notes-controller.mjs', 'docs/reviews/src/features/notes-controller.test.mjs'];
const sourceHashes = () => Object.fromEntries(sources.map(path => [path, hash(read(path))]));
const status = JSON.parse(execFileSync(process.execPath, ['docs/reviews/open.mjs', '--status'], { cwd: root, encoding: 'utf8' }));
assert.equal(status.active, false, 'Do not package over a live managed review');
const before = { notes: notes(), sourceHashes: sourceHashes(), outputs: Object.fromEntries(outputs.map(path => [path, hash(read(path))])) };
mkdirSync(resolve(cache, 'before'), { recursive: true });
for (let i = 0; i < outputs.length; i++) copyFileSync(resolve(root, outputs[i]), resolve(cache, 'before', i + '-' + outputs[i].split('/').at(-1)));
writeFileSync(resolve(cache, 'before.json'), JSON.stringify(before, null, 2) + '\n');
const buildOutput = execFileSync(process.execPath, ['docs/planning/2026-10-09/review-site/src/pages/build.mjs'], { cwd: root, encoding: 'utf8' });
writeFileSync(resolve(cache, 'build.stdout'), buildOutput);
assert.deepEqual(notes(), before.notes, 'Reviewer notes changed');
assert.deepEqual(sourceHashes(), before.sourceHashes, 'Source changed during packaging');
const htmlBytes = read(outputs[0]);
const html = htmlBytes.toString('utf8');
const report = JSON.parse(read(outputs[1]));
const version = JSON.parse(read(outputs[2]));
assert.equal(hash(htmlBytes), report.sha256);
assert.equal(htmlBytes.length, report.bytes);
assert.equal(report.documentVersion, version.version);
assert.equal(version.sourceHashes['notes-controller.mjs'], before.sourceHashes[sources[0]]);
assert.ok(html.includes("if (reviewData.bridge || canStore || !unsharedChanges || !hasText()) return;"));
const controller = read(sources[0]).toString('utf8').replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
assert.ok(html.includes(controller), 'Complete current notes controller is not embedded');
assert.ok(html.includes('Saving to your repository file…'));
assert.equal((html.match(/<section\b[^>]*\bid="0[1-6]-/g) || []).length, 6);
const images = [...html.matchAll(/data:image\/png;base64,([A-Za-z0-9+/=]+)/g)].map(match => hash(Buffer.from(match[1], 'base64')));
for (const digest of Object.values(report.imageHashes)) assert.ok(images.includes(digest));
assert.equal(Object.keys(report.imageHashes).length, 6);
const plan = /data:text\/markdown;charset=utf-8;base64,([A-Za-z0-9+/=]+)/.exec(html);
assert.ok(plan);
assert.equal(hash(Buffer.from(plan[1], 'base64')), hash(read('docs/planning/2026-10-09/implementation-plan.md')));
assert.equal(report.planSha256, hash(read('docs/planning/2026-10-09/implementation-plan.md')));
assert.equal(report.logoSha256, hash(read('dashboard/assets/logo-ccc.svg')));
assert.ok(html.includes('data:image/svg+xml;base64,' + read('dashboard/assets/logo-ccc.svg').toString('base64')));
assert.ok(!/<script\b[^>]*\bsrc\s*=/i.test(html));
assert.ok(!/<link\b[^>]*\brel=["']stylesheet["']/i.test(html));
assert.ok(!/\{\{(?:LOGO_DATA_URI|SCENES|PLAN_DATA_URI|SCENE_CSS|REVIEW_SCRIPT|REVIEW_DATA|NOTES_RUNTIME)\}\}/.test(html));
let scriptsChecked = 0;
for (const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
  if (/type=["']application\/json["']/i.test(match[1])) continue;
  new Script(match[2]); scriptsChecked++;
}
assert.ok(scriptsChecked > 0);
const afterStatus = JSON.parse(execFileSync(process.execPath, ['docs/reviews/open.mjs', '--status'], { cwd: root, encoding: 'utf8' }));
assert.equal(afterStatus.active, false);
const result = { scope: 'Existing review packaging and offline artifact checks only', before, after: { notes: notes(), sourceHashes: sourceHashes(), outputs: Object.fromEntries(outputs.map(path => [path, hash(read(path))])) }, documentVersion: version.version, htmlBytes: htmlBytes.length, imageHashesVerified: 6, embeddedPlanAndUnchangedLogoVerified: true, completeCurrentNotesControllerEmbedded: true, inlineScriptsSyntaxChecked: scriptsChecked, managedServerInactiveBeforeAndAfter: true, notesAndSourceUnchanged: true, browserStorageAccessed: false, fullTestsRerun: false, runtimeExecuted: false, phaseAccepted: false };
writeFileSync(resolve(cache, 'review.json'), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify({ report: resolve(cache, 'review.json'), reportSHA256: hash(readFileSync(resolve(cache, 'review.json'))), documentVersion: version.version, htmlSHA256: report.sha256, notesUnchanged: true }));
